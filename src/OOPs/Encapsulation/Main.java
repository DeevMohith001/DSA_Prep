// Encapsulation --> Wrapping up the implementation of the data members and the methods inside a class.
// It basically hides the code or data into a single entity or a unit so that can be protected from the outside world.

// Abstraction vs Encapsulation -->
//      Abstraction is solving a design level issue. Encapsulation is solving an implementation issue.

// Encapsulation is hiding something internally, Abstraction will provide some of the outside methods we can use.
// Abstraction focuses on the external stuff, and encapsulation focuses on the internal working.
// Abstraction is the process of gaining information, Encapsulation is a process of containing the information.

// Data hiding and Encapsulation:
//      Data hiding focuses on data security. e.g. private keyword.
//      Encapsulation focuses on hiding the complexity of the system. here data can be public or private.
//      Encapsulation is a process in data hiding.